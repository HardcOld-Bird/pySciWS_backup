# %% 个人每日 Token 用量转录与合计（用户 2026-10-12 提供原始数据，组长代录，2026-09-27 ~ 10-11）
# 单位：tokens。缓存命中率 = 缓存输入 / (未缓存输入 + 缓存输入)。
from pathlib import Path
import pandas as pd
from pysci.paths import assert_within_data

OUT_DIR = Path(__file__).resolve().parent
assert_within_data(OUT_DIR)

# 列：日期, 未缓存输入, 缓存输入, 输出
USAGE = [
    ("2026-09-27",  2032834,  15913780,   218140),
    ("2026-09-28",  2801579,  61444525,   668675),
    ("2026-09-29",   989573,  21701959,   280304),
    ("2026-09-30",  2751243,  31014839,   801101),
    ("2026-10-01",  4053394,  80911064,  1080696),
    ("2026-10-02",  3541227,  56097361,   933552),
    ("2026-10-03",  5205828, 156520280,  1728549),
    ("2026-10-04",  3091639,  93735026,  1047818),
    ("2026-10-05",  1443056,  14873467,   179208),
    ("2026-10-06",  1441568,  10564025,    80133),
    ("2026-10-07",   192050,    697767,    21414),
    ("2026-10-08",   416398,   2060396,    18603),
    ("2026-10-09",  4306255,  66379224,   224396),
    ("2026-10-10", 17308288, 160255322,   498381),
    ("2026-10-11", 1211415,   4446544,   111513),
]

df = pd.DataFrame(USAGE, columns=["日期", "未缓存输入", "缓存输入", "输出"])
df.insert(2, "缓存命中率%", (df["缓存输入"] / (df["未缓存输入"] + df["缓存输入"]) * 100).round(1))
df["总Tokens"] = df["未缓存输入"] + df["缓存输入"] + df["输出"]
df = df[["日期", "总Tokens", "缓存命中率%", "未缓存输入", "缓存输入", "输出"]]

df.to_csv(OUT_DIR / "个人每日Token用量.csv", index=False, encoding="utf-8-sig")

print(df.to_string(index=False))
print("\n—— 合计（15 天）——")
for col in ["总Tokens", "未缓存输入", "缓存输入", "输出"]:
    print(f"{col}: {df[col].sum():,}")
print(f"整体缓存命中率: {df['缓存输入'].sum() / (df['未缓存输入'].sum() + df['缓存输入'].sum()) * 100:.1f}%")
print(f"日均总Tokens: {df['总Tokens'].mean():,.0f}")
