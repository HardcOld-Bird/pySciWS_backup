"""refs_bridge 机械断言：固定 Zotero/CSL 样例 → BibTeX 确定性转换。"""

from __future__ import annotations

import json

import pytest

from pysci.skills.document_writing import refs_bridge

# 固定样例 1：Zotero JSON 条目（zotero-cli --json 导出形态）
ZOTERO_ITEM = {
    "itemType": "journalArticle",
    "title": "Deep Learning for Molecules",
    "creators": [
        {"firstName": "John", "lastName": "Smith", "creatorType": "author"},
        {"firstName": "Jane", "lastName": "Doe", "creatorType": "author"},
        {"firstName": "Ed", "lastName": "Editor", "creatorType": "editor"},
    ],
    "publicationTitle": "Nature chemistry",
    "date": "2021-05-02",
    "volume": "13",
    "issue": "4",
    "pages": "100-110",
    "DOI": "10.1038/s41557-021-00000-x",
    "url": "https://example.org/a",
}

# 固定样例 2：CSL JSON 条目（Zotero 导出格式 "CSL JSON"）
CSL_ITEM = {
    "type": "paper-conference",
    "title": "Graph Networks",
    "author": [{"family": "Wang", "given": "Wei"}],
    "container-title": "NeurIPS",
    "issued": {"date-parts": [[2020]]},
    "page": "1-9",
}


def test_normalize_zotero_item():
    entry_type, hint, fields = refs_bridge.normalize_item(ZOTERO_ITEM)
    assert entry_type == "article"
    assert fields["author"] == "Smith, John and Doe, Jane"
    assert fields["editor"] == "Editor, Ed"
    assert fields["journal"] == "Nature chemistry"  # 空格不转义
    assert fields["year"] == "2021"
    assert fields["volume"] == "13"
    assert fields["number"] == "4"
    assert fields["pages"] == "100-110"
    assert fields["doi"] == "10.1038/s41557-021-00000-x"
    assert "Smith" in hint and "2021" in hint and "Deep" in hint


def test_normalize_csl_item():
    entry_type, hint, fields = refs_bridge.normalize_item(CSL_ITEM)
    assert entry_type == "inproceedings"
    assert fields["author"] == "Wang, Wei"
    assert fields["booktitle"] == "NeurIPS"
    assert fields["year"] == "2020"
    assert fields["pages"] == "1-9"
    assert "Wang" in hint


def test_escape_tex_specials():
    got = refs_bridge.escape_tex("A & B 100% _x_ {y} #1 $2 ~ ^ \\")
    assert r"\&" in got and r"\%" in got and r"\_" in got
    assert r"\{" in got and r"\}" in got and r"\#" in got and r"\$" in got
    assert r"\textbackslash{}" in got
    assert r"\textasciitilde{}" in got and r"\textasciicircum{}" in got


def test_escape_tex_collapses_whitespace():
    assert refs_bridge.escape_tex("a\n  b\tc") == "a b c"


def test_unknown_item_raises():
    with pytest.raises(refs_bridge.RefsError):
        refs_bridge.normalize_item({"foo": "bar"})


def test_item_to_bibtex_field_order():
    text = refs_bridge.item_to_bibtex(
        "article", "smith2021deep",
        {"title": "T", "author": "A", "year": "2021", "journal": "J"},
    )
    head = "@article{smith2021deep,"
    assert text.startswith(head)
    order = [text.index(f"  {name} =") for name in ("author", "title", "journal", "year")]
    assert order == sorted(order)


def test_write_refs_bib_deterministic_and_key_dedupe(tmp_path):
    item2 = dict(ZOTERO_ITEM)  # 同 hint（同姓/年/标题词）→ key 追加后缀
    items = [ZOTERO_ITEM, item2, CSL_ITEM]
    out1 = refs_bridge.write_refs_bib(items, tmp_path / "refs.bib")
    first = out1.read_text(encoding="utf-8")
    out2 = refs_bridge.write_refs_bib(items, tmp_path / "refs.bib")
    assert first == out2.read_text(encoding="utf-8")
    assert first.startswith("% generated by pysci-doc refs")
    assert first.count("@article{") == 2
    assert "@inproceedings{wang2020graph," in first
    keys = [
        line.split("{", 1)[1].rstrip(",")
        for line in first.splitlines()
        if line.startswith("@")
    ]
    assert keys == sorted(keys)
    assert "smith2021deep" in keys and "smith2021deepa" in keys


def test_load_items_accepts_items_container(tmp_path):
    path = tmp_path / "items.json"
    path.write_text(json.dumps({"items": [CSL_ITEM]}), encoding="utf-8")
    assert refs_bridge.load_items(path) == [CSL_ITEM]


def test_load_items_rejects_bad_shape(tmp_path):
    path = tmp_path / "bad.json"
    path.write_text(json.dumps({"oops": 1}), encoding="utf-8")
    with pytest.raises(refs_bridge.RefsError):
        refs_bridge.load_items(path)
