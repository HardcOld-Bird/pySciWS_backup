// Generate pysci/standard.plugins.yml and pysci/cordis.plugins.yml from the
// upstream DSH web-app presets. Run after every DSH upgrade.
//
// Usage: node sub_root/deps_management/deps_manager/scripts/extract_presets.mjs [--check]
// Exit 1 on --check drift.

import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const upstreamDir = path.join(
  root,
  'sub_root/deps_management/deps/node/modules/node_modules/@deepseek-ai/dsh-web-app/presets',
)
const outDir = path.join(
  root,
  'sub_root/deps_management/deps/node/modules/dsh_home/profiles/web/pysci',
)

const targets = [
  { source: 'standard.patch.yml', out: 'standard.plugins.yml', preset: 'standard' },
  { source: 'cordis.patch.yml', out: 'cordis.plugins.yml', preset: 'cordis' },
]

function extractPlugins(file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/)
  const start = lines.findIndex((line) => /^ {8}plugins:\s*$/.test(line))
  if (start < 0) throw new Error(`plugins: block not found in ${file}`)
  const body = []
  for (let i = start + 1; i < lines.length; i += 1) {
    const line = lines[i]
    if (line.trim() === '') {
      body.push('')
      continue
    }
    const indent = line.match(/^ */)[0].length
    if (indent <= 8) break
    body.push(line.replace(/^ {10}/, ''))
  }
  while (body.length > 0 && body[body.length - 1] === '') body.pop()
  return body.join('\n') + '\n'
}

function rendered(target) {
  const header = [
    '# GENERATED by deps_manager/scripts/extract_presets.mjs — do not edit by hand.',
    `# source: @deepseek-ai/dsh-web-app/presets/${target.source}`,
    `# preset: ${target.preset}  mode: plugins`,
    "# Re-run after every DSH upgrade; overrides belong in the include row's `patches`.",
    '',
  ].join('\n')
  return header + extractPlugins(path.join(upstreamDir, target.source))
}

const check = process.argv.includes('--check')
if (!check) fs.mkdirSync(outDir, { recursive: true })

let drift = false
for (const target of targets) {
  const outPath = path.join(outDir, target.out)
  const next = rendered(target)
  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
  if (check) {
    if (prev !== next) {
      drift = true
      console.error(`[extract_presets] drift: ${outPath}`)
    } else {
      console.log(`[extract_presets] ok: ${target.out}`)
    }
  } else {
    fs.writeFileSync(outPath, next, 'utf8')
    console.log(`[extract_presets] wrote ${outPath}`)
  }
}

if (check && drift) process.exit(1)
